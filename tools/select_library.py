"""Library v2 selection (user, 11 Nov 2026): cut the Pullback and Mean-reversion families to 100 systems each WITHOUT looking
at any return, so the cut cannot favour lucky systems.

Rule (pre-registered before running it):
  1. Reference panel: H4 bars of EURUSD, USDJPY, XAUUSD, US500, BTCUSD, USOIL from 2019-07-16 to 2026-09-30.
  2. Each system's signals with its default parameters (first value of each signal parameter in its grid); the direction of
     every signal (+1 / -1) is summed per calendar day and the six markets are put side by side -> one signal vector.
  3. A system that fires fewer than 60 times on the whole panel is left out (it could never give 30 OOS trades).
  4. Greedy max-diversity: start with the system whose mean |correlation| with the rest of its family is lowest; then
     repeatedly add the system whose highest |correlation| with the systems already chosen is lowest (ties: lowest number).
  5. Stop at 100 per family. Writes app/library_v2.py (KEEP) and data/research/library_v2_selection.json.
Only signal timing is used — never P/L, OOS or any research result.

    python -m tools.select_library
"""
from __future__ import annotations

import json
import sys

import numpy as np
import pandas as pd

PANEL = ["EURUSD", "USDJPY", "XAUUSD", "US500", "BTCUSD", "USOIL"]
START, END = "2019-07-16", "2026-09-30"
FAMILIES = ("Pullback", "Mean reversion")
TARGET, MIN_SIG = 100, 60
# systems that failed tests/check_strategies after the selection (11 Nov 2026: mr_stochf_year, random-walk mean +0.085 R
# with the v2 exit grid): removed, and the family is topped up with the next pick of the same greedy order
FAILED_CHECKS = {"mr_stochf_year"}


def main() -> int:
    from app import data
    from app.strategies import STRATEGIES
    frames = {s: data.get_bars(s, "H4") for s in PANEL}
    frames = {s: d[(d.index >= START) & (d.index < END)] for s, d in frames.items()}
    days = {s: pd.DatetimeIndex(sorted(set(d.index.normalize()))) for s, d in frames.items()}
    out, report = {}, {}
    for fam in FAMILIES:
        ids = sorted([k for k, v in STRATEGIES.items() if v["family"] == fam], key=lambda k: STRATEGIES[k]["no"])
        vecs, counts = {}, {}
        for k in ids:
            v = STRATEGIES[k]
            p = {kk: vv[0] for kk, vv in v["grid"].items() if kk not in ("sl_atr", "rr")}
            parts, n = [], 0
            for s, d in frames.items():
                sig, _ = v["fn"](d, p)
                sig = np.nan_to_num(np.asarray(sig, float))
                n += int((sig != 0).sum())
                parts.append(pd.Series(sig, index=d.index.normalize()).groupby(level=0).sum().reindex(days[s], fill_value=0).to_numpy())
            counts[k] = n
            if n >= MIN_SIG:
                vecs[k] = np.concatenate(parts)
        keys = list(vecs)
        M = np.array([vecs[k] for k in keys], float)
        C = np.abs(np.nan_to_num(np.corrcoef(M)))
        np.fill_diagonal(C, 0)
        no = np.array([STRATEGIES[k]["no"] for k in keys])
        first = int(np.lexsort((no, C.mean(axis=1)))[0])
        chosen = [first]
        maxc = C[first].copy()
        want = TARGET + sum(1 for k in keys if k in FAILED_CHECKS)
        while len(chosen) < min(want, len(keys)) or (len([j for j in chosen if keys[j] not in FAILED_CHECKS]) < TARGET
                                                     and len(chosen) < len(keys)):
            m = maxc.copy()
            m[chosen] = np.inf
            j = int(np.lexsort((no, m))[0])
            chosen.append(j)
            maxc = np.maximum(maxc, C[j])
        order = [keys[j] for j in chosen]
        keep = sorted([k for k in order if k not in FAILED_CHECKS][:TARGET], key=lambda k: STRATEGIES[k]["no"])
        out[fam] = keep
        sub = C[np.ix_(chosen, chosen)]
        report[fam] = {"candidates": len(ids), "fired_enough": len(keys), "kept": len(keep),
                       "too_few_signals": [k for k in ids if counts[k] < MIN_SIG],
                       "mean_abs_corr_all": round(float(C[np.triu_indices(len(keys), 1)].mean()), 3),
                       "mean_abs_corr_kept": round(float(sub[np.triu_indices(len(chosen), 1)].mean()), 3),
                       "max_abs_corr_kept": round(float(sub.max()), 3), "keep": keep}
        print(f"{fam}: {len(ids)} systems, {len(keys)} fire >= {MIN_SIG}, kept {len(keep)} · mean |corr| "
              f"{report[fam]['mean_abs_corr_all']} -> {report[fam]['mean_abs_corr_kept']} (max {report[fam]['max_abs_corr_kept']})")
    with open("app/library_v2.py", "w") as f:
        f.write('"""Generated by tools/select_library.py (library v2, 11 Nov 2026) — the 100 Pullback and 100 Mean-reversion systems\n'
                'kept by the signal-diversity rule (no returns used). Do not edit by hand."""\n')
        f.write("KEEP: dict = " + json.dumps(out, indent=1) + "\n")
    with open("data/research/library_v2_selection.json", "w") as f:
        json.dump({"rule": __doc__, "panel": PANEL, "from": START, "to": END, **report}, f, ensure_ascii=False, indent=1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
